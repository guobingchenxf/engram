def render_explain_html(explanation: dict[str, Any]) -> str:
    rows: list[str] = []
    for item in explanation.get("influences", []):
        influence = float(item.get("influence", 0.0))
        css = "inf" if influence > 0 else "zero"
        rows.append(
            "<tr>"
            f"<td class='{css}'>{influence:.1f}</td>"
            f"<td><code>{html.escape(str(item.get('content', '')))}</code></td>"
            f"<td><code>{html.escape(str(item.get('without_answer', '')))}</code></td>"
            "</tr>"
        )
    if not rows:
        rows.append("<tr><td colspan='3' class='zero'>No retrieved memories.</td></tr>")

    fidelity = explanation.get("fidelity", {})
    fidelity_text = (
        f"{float(fidelity.get('fidelity@1', 0.0)):.0%} / "
        f"{float(fidelity.get('fidelity@2', 0.0)):.0%}"
    )
    return (
        _EXPLAIN_TEMPLATE.replace("__QUERY__", html.escape(str(explanation.get("query", ""))))
        .replace("__BASE__", html.escape(str(explanation.get("base_answer", ""))))
        .replace("__HITS__", str(explanation.get("hits", 0)))
        .replace("__METHOD__", html.escape(str(explanation.get("method", ""))))
        .replace("__FIDELITY__", fidelity_text)
        .replace("__ROWS__", "\n".join(rows))
    )
