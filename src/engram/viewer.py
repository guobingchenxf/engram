def render_trace_html(
    events: Sequence[dict[str, Any]],
    *,
    title: str = "Engram trace",
) -> str:
    rows: list[str] = []
    writes = searches = denied = 0
    for event in events:
        event_name = str(event.get("event", "unknown"))
        if event_name == "write":
            writes += 1
        elif event_name == "search":
            searches += 1
        if event_name in {"write_denied", "update_denied", "extract_skipped"}:
            denied += 1

        payload = {
            key: value
            for key, value in event.items()
            if key not in {"ts", "event", "user_id", "memory_id"}
        }
        payload_json = json.dumps(payload, ensure_ascii=False, default=str)
        css_class = "denied" if event_name in {"write_denied", "update_denied"} else "event"
        rows.append(
            "<tr>"
            f"<td>{html.escape(str(event.get('ts', '')))}</td>"
            f"<td class='{css_class}'>{html.escape(event_name)}</td>"
            f"<td>{html.escape(str(event.get('user_id', '')))}</td>"
            f"<td>{html.escape(str(event.get('memory_id', '')))}</td>"
            f"<td><code>{html.escape(payload_json)}</code></td>"
            "</tr>"
        )

    empty = (
        "<div class='empty'>No trace events yet. Write or search a memory first.</div>"
        if not rows
        else ""
    )
    return (
        _TEMPLATE.replace("__TITLE__", html.escape(title))
        .replace("__COUNT__", str(len(rows)))
        .replace("__WRITES__", str(writes))
        .replace("__SEARCHES__", str(searches))
        .replace("__DENIED__", str(denied))
        .replace("__ROWS__", "\n".join(rows))
        .replace("__EMPTY__", empty)
    )


def render_trace_file(path: str, *, limit: int = 200) -> str:
    from .trace import TraceLogger

    return render_trace_html(TraceLogger(path).read(limit=limit))


