def render_benchmark_html(report: BenchmarkReport) -> str:
    memory = report.aggregate(report.results)
    baseline = report.aggregate(report.baseline_results)
    conditions: list[tuple[str, dict[str, Any]]] = [
        ("memory", memory),
        ("full-history", baseline),
    ]
    for name, results in report.ablations.items():
        conditions.append((name, report.aggregate(results)))

    cards = [
        ("memory pass rate", f"{memory['check_pass_rate']:.0%}"),
        ("baseline pass rate", f"{baseline['check_pass_rate']:.0%}"),
        ("scenarios", f"{memory['scenarios_passed']}/{memory['scenarios']}"),
        ("checks", f"{memory['checks_passed']}/{memory['checks']}"),
        ("avg tokens", f"{memory['avg_tokens']:.1f}"),
    ]
    cards_html = "\n".join(
        f"<div class='card'><div class='label'>{html.escape(label)}</div>"
        f"<div class='value'>{html.escape(value)}</div></div>"
        for label, value in cards
    )

    bars: list[str] = []
    for label, aggregate in conditions:
        rate = float(aggregate["check_pass_rate"])
        width = max(0.0, min(100.0, rate * 100))
        bars.append(
            "<div class='bar-row'>"
            f"<div class='bar-label'>{html.escape(label)}</div>"
            f"<div class='bar-track'><div class='bar-fill' style='width:{width:.1f}%'></div></div>"
            f"<div class='bar-value'>{rate:.0%}</div>"
            "</div>"
        )

    categories = []
    for name, bucket in sorted(memory["by_category"].items()):
        total = int(bucket["total"])
        passed = int(bucket["passed"])
        rate = passed / total if total else 0.0
        categories.append(
            "<div class='cat'>"
            f"<div class='top'><span>{html.escape(name)}</span><span>{passed}/{total}</span></div>"
            f"<div class='track'><div class='fill' style='width:{rate * 100:.1f}%'></div></div>"
            "</div>"
        )

    scenario_cells = []
    for result in report.results:
        css = "pass" if result.passed else "fail"
        scenario_cells.append(
            f"<div class='cell {css}' title='{html.escape(result.category)}'>"
            f"<span class='dot'></span>{html.escape(result.scenario_id)}"
            "</div>"
        )

    failures: list[str] = []
    for result in report.results:
        for check in result.checks:
            if check.passed:
                continue
            detail = []
            if check.missing:
                detail.append("missing " + ", ".join(check.missing))
            if check.forbidden:
                detail.append("forbidden " + ", ".join(check.forbidden))
            failures.append(
                f"<li><strong>{html.escape(result.scenario_id)}</strong> / "
                f"{html.escape(check.query)}"
                + (f" — {html.escape('; '.join(detail))}" if detail else "")
                + "</li>"
            )
    failures_html = (
        "<ul class='failures'>" + "\n".join(failures) + "</ul>"
        if failures
        else "<div class='empty'>No failures.</div>"
    )

    subtitle = (
        f"{memory['scenarios']} scenarios · memory {memory['scenarios_passed']}/"
        f"{memory['scenarios']} · full-history {baseline['scenarios_passed']}/"
        f"{baseline['scenarios']} · ablations {len(report.ablations)}"
    )
    import datetime

    generated = datetime.datetime.now().isoformat(timespec="seconds")
    return (
        _BENCH_TEMPLATE.replace("__SUBTITLE__", html.escape(subtitle))
        .replace("__CARDS__", cards_html)
        .replace("__BARS__", "\n".join(bars))
        .replace("__CATEGORIES__", "\n".join(categories))
        .replace("__SCENARIOS__", "\n".join(scenario_cells))
        .replace("__FAILURES__", failures_html)
        .replace("__GENERATED__", html.escape(generated))
    )


